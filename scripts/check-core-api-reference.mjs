import { createRequire } from "node:module"
import { fileURLToPath, pathToFileURL } from "node:url"
import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import process from "node:process"

import ts from "typescript"

const root = process.cwd()
const docsPath = path.join(root, "docs/api/core.md")
const sourcePath = path.join(root, "packages/core/src/index.ts")
const declarationPaths = ["index.d.ts", "index.d.mts", "index.d.cts"].map((file) =>
  path.join(root, "packages/core/dist", file)
)
const startMarker = "<!-- core-root-exports:start -->"
const endMarker = "<!-- core-root-exports:end -->"

export function collectExports(source, filename = "index.ts") {
  const file = ts.createSourceFile(filename, source, ts.ScriptTarget.Latest, true)
  const exports = new Map()

  for (const statement of file.statements) {
    if (
      ts.isExportDeclaration(statement) &&
      statement.exportClause &&
      ts.isNamedExports(statement.exportClause)
    ) {
      for (const element of statement.exportClause.elements) {
        exports.set(
          element.name.text,
          statement.isTypeOnly || element.isTypeOnly ? "type" : "runtime"
        )
      }
      continue
    }
    if (!hasExportModifier(statement)) continue
    if (
      ts.isFunctionDeclaration(statement) ||
      ts.isClassDeclaration(statement) ||
      ts.isEnumDeclaration(statement)
    ) {
      if (statement.name) exports.set(statement.name.text, "runtime")
      continue
    }
    if (ts.isVariableStatement(statement)) {
      for (const declaration of statement.declarationList.declarations) {
        if (ts.isIdentifier(declaration.name)) exports.set(declaration.name.text, "runtime")
      }
    }
  }

  return [...exports.entries()]
    .map(([name, kind]) => ({ name, kind }))
    .sort((left, right) => left.name.localeCompare(right.name))
}

export function renderExportBlock(exports) {
  const rows = exports.map(({ name, kind }) => ({
    name: `\`${name}\``,
    kind: kind === "runtime" ? "Runtime" : "Type-only",
  }))
  const exportWidth = Math.max("Export".length, ...rows.map(({ name }) => name.length))
  const kindWidth = Math.max("Kind".length, ...rows.map(({ kind }) => kind.length))
  const row = (name, kind) => `| ${name.padEnd(exportWidth)} | ${kind.padEnd(kindWidth)} |`
  return [
    startMarker,
    "<!-- Generated by scripts/check-core-api-reference.mjs. Do not edit manually. -->",
    "",
    row("Export", "Kind"),
    row("-".repeat(exportWidth), "-".repeat(kindWidth)),
    ...rows.map(({ name, kind }) => row(name, kind)),
    "",
    endMarker,
  ].join("\n")
}

export function replaceExportBlock(docs, block) {
  const start = docs.indexOf(startMarker)
  const end = docs.indexOf(endMarker)
  if (start === -1 || end === -1 || end < start) {
    throw new Error("docs/api/core.md is missing the core root export markers.")
  }
  return `${docs.slice(0, start)}${block}${docs.slice(end + endMarker.length)}`
}

function hasExportModifier(statement) {
  return (
    statement.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword) ?? false
  )
}

function assertSameNames(expected, actual, label) {
  const expectedNames = expected.map(({ name }) => name).sort()
  const actualNames = actual.map(({ name }) => name).sort()
  if (expectedNames.join("\n") !== actualNames.join("\n")) {
    throw new Error(`${label} does not match packages/core/src/index.ts root exports.`)
  }
}

async function check() {
  const sourceExports = collectExports(readFileSync(sourcePath, "utf8"), sourcePath)
  const docs = readFileSync(docsPath, "utf8")
  const block = renderExportBlock(sourceExports)

  for (const declarationPath of declarationPaths) {
    assertSameNames(
      sourceExports,
      collectExports(readFileSync(declarationPath, "utf8"), declarationPath),
      declarationPath
    )
  }

  const esm = await import(pathToFileUrl(path.join(root, "packages/core/dist/index.mjs")))
  const require = createRequire(import.meta.url)
  const cjs = require(path.join(root, "packages/core/dist/index.cjs"))
  const runtime = sourceExports.filter(({ kind }) => kind === "runtime")
  assertSameNames(
    runtime,
    Object.keys(esm).map((name) => ({ name })),
    "ESM root runtime exports"
  )
  assertSameNames(
    runtime,
    Object.keys(cjs).map((name) => ({ name })),
    "CJS root runtime exports"
  )

  if (docs !== replaceExportBlock(docs, block)) {
    throw new Error(
      "docs/api/core.md root export table has drifted; run pnpm check:core-api-reference --write."
    )
  }
}

function pathToFileUrl(file) {
  return pathToFileURL(file).href
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--write")) {
    const sourceExports = collectExports(readFileSync(sourcePath, "utf8"), sourcePath)
    writeFileSync(
      docsPath,
      replaceExportBlock(readFileSync(docsPath, "utf8"), renderExportBlock(sourceExports))
    )
  } else {
    await check()
    console.log("@palamedes/core root API docs match source, declarations, ESM, and CJS exports.")
  }
}
